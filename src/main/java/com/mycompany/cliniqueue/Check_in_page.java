    private void jLabel10MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jLabel10MouseClicked
        // TODO add your handling code here:
         String name = nameText.getText();
        String surname = surnameText.getText();
        String idNum = idText.getText();
     
        
        if(name.isBlank() || surname.isBlank() || idNum.isBlank()){
            JOptionPane.showMessageDialog(null, "field can't be empty");
        }
        else if(idNum.length()<13 || idNum.length()>13 || !idNum.matches("\\d+")){
            JOptionPane.showMessageDialog(null, "ID must be 13 numbers only");
        }
        
        //else if(!coughText.isSelected() && !painText.isSelected() && !feverText.isSelected() && !otherText.isSelected()){
         //   JOptionPane.showMessageDialog(null, "select one option that applies to you");
        //}
            
        else{
            ReasonForVisit reason = new ReasonForVisit(name, surname, idNum);
            reason.setVisible(true);
            this.dispose();
        }
    }//GEN-LAST:event_jLabel10MouseClicked

